-- 직원(staff) 권한 두 가지 추가
--
-- [2026-09-28 사용자 지시] 관리자가 **이메일로 계정을 골라 권한을 주는** 방식으로
-- 직원을 만든다. 역할(user_role)을 새로 만들지 않고 기존 기능 권한
-- (user_permissions)에 값을 더하는 이유:
--   · 역할은 계정당 하나라, "상담만 보는 직원"과 "업체 승인까지 하는 직원"을
--     나눌 수 없다. 권한은 기능별로 켜고 끌 수 있다.
--   · 이미 MY > 운영 > 등록권한 계정관리 화면이 이 표를 토글하고 있다 —
--     같은 화면에 항목만 늘면 된다.
--
-- 이 파일은 enum 값만 더한다. **값을 쓰는 함수는 다음 파일에 있다** —
-- Postgres는 새 enum 값을 추가한 트랜잭션 안에서 그 값을 쓰지 못한다.
-- ============================================================================

alter type public.user_permission_type add value if not exists 'chat_support';
alter type public.user_permission_type add value if not exists 'agency_manage';
