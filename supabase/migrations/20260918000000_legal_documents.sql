-- 본문을 i18n이나 코드에 박지 않는 이유: 원문이 베트남 법무법인에서 **출시 직전에**
-- 온다. 코드에 있으면 그때 재빌드 + 재심사를 해야 하지만, 글로 두면 관리자 화면에서
-- 붙여넣는 것으로 끝난다. 기존 자동 번역 파이프라인(6개 언어)도 그대로 탄다.
--
-- 개정하면 새 글을 올리고 이전 글은 published=false로 내린다 — 개정 이력이 그대로
-- 남고, 화면은 "공개된 것 중 가장 최근 글"을 보여 준다(services/boards.ts).
--
-- 화면·메뉴는 app/legal/[kind].tsx, MY → 설정. 공개 게시판 탭에는 넣지 않았다 —
-- 목록으로 훑는 글이 아니라 필요할 때 찾아 들어가 읽는 문서다.
--
-- ---------------------------------------------------------------------------
-- 이 파일은 **두 번에 나눠** 실행한다.
--
-- PostgreSQL에서 ALTER TYPE ... ADD VALUE로 추가한 enum 값은 그 트랜잭션이 커밋된
-- 뒤에야 쓸 수 있다. 한 번에 실행하면 2단계의 'terms'가 아직 없는 값이라 실패한다.
--
--   1단계: 2026-09-14 적용 완료
--   2단계: 아래
-- ---------------------------------------------------------------------------


-- ===========================================================================
-- 1단계 — enum 확장 (적용 완료)
-- ===========================================================================

alter type public.board_kind add value if not exists 'terms';
alter type public.board_kind add value if not exists 'privacy';


-- ===========================================================================
-- 2단계 — 자리 잡아 두기
-- ===========================================================================

-- 본문에는 "준비 중"만 넣는다.
--
-- 작업용 초안(claude/legal-*.md)을 그대로 넣지 않는 이유: 그 문서는 빈칸을 채우기
-- 위한 것이라 【수정 필요】 표시가 가득하다. 앱 화면에 띄우면 이용자에게는 읽을 수
-- 없는 글이 되고, 심사자가 보면 미완성 앱으로 읽힌다. 초안은 법무법인에 넘기는
-- 파일로 두고, 화면에는 상태를 솔직하게 적는다.
--
-- 이 상태로도 테스트할 것은 다 된다 — 메뉴 진입, 화면 렌더, 언어 전환, 빈/정상 상태.
-- 원문이 오면 관리자 → 게시판 관리 → 이용약관에서 본문만 바꾸면 되고, 그때 6개 언어
-- 번역도 저장과 함께 자동으로 만들어진다. **앱 재빌드는 필요 없다.**

insert into public.board_posts (kind, title, body, source_lang, pinned, published)
select
  'terms',
  '이용약관',
  E'준비 중입니다.\n\n이용약관은 베트남 법무법인의 검토를 거쳐 서비스 정식 출시 전에 등록됩니다.\n\n문의: 관리자에게 연락해 주십시오.',
  'ko', false, true
where not exists (select 1 from public.board_posts where kind = 'terms');

insert into public.board_posts (kind, title, body, source_lang, pinned, published)
select
  'privacy',
  '개인정보처리방침',
  E'준비 중입니다.\n\n개인정보처리방침은 베트남 법무법인의 검토를 거쳐 서비스 정식 출시 전에 등록됩니다.\n\n현재 서비스가 수집하는 정보와 처리 방식은 등록 시점에 이 화면에 상세히 안내됩니다.\n\n문의: 관리자에게 연락해 주십시오.',
  'ko', false, true
where not exists (select 1 from public.board_posts where kind = 'privacy');
